import { test, expect } from '@playwright/test'
const origin = 'http://127.0.0.1:3100'
const password = 'test-only-xiaojueshi-2026'
test('写作、自动保存、发布、隔离、撤回与备份恢复', async ({ page, request, playwright }, testInfo) => {
  expect((await request.get('/api/admin/content')).status()).toBe(401)
  await page.goto('/admin')
  await page.locator('[data-app-ready="true"]').waitFor()
  await page.getByLabel(/管理员密码/).fill(password)
  await page.getByRole('button', { name: /设置密码并进入|进入工作台/ }).click()
  await expect(page.getByRole('heading', { name: '内容工作台' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('admin-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '私密', exact: true }).click()
  await expect(page.getByRole('heading', { name: '内容工作台' })).toBeVisible()
  await page.getByRole('button', { name: '全部', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('admin-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.getByRole('button', { name: '新建记录' }).last().click()
  const title = `测试记录-${Date.now()}`
  await page.getByLabel('内容标题').fill(title)
  await page.getByLabel('Markdown 正文').fill('# 测试正文\n\n私人文字，仅管理员可见。')
  await expect(page.getByRole('status').filter({ hasText: '所有更改已保存' })).toBeVisible()
  const records = await page.request.get('/api/admin/content').then(r => r.json())
  const record = records.find((d: any) => d.title === title)
  expect(record.visibility).toBe('private')
  const imageResponse = await page.request.post('/api/admin/upload', { headers: { origin }, multipart: { contentId: record.id, file: { name: 'pixel.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aH0sAAAAASUVORK5CYII=', 'base64') } } })
  expect(imageResponse.ok()).toBeTruthy()
  const image = await imageResponse.json()
  expect((await request.get(image.url)).status()).toBe(404)
  expect((await page.request.get(image.url)).status()).toBe(200)
  await page.getByLabel('Markdown 正文').fill(`# 测试正文\n\n私人文字，仅管理员可见。\n\n![图片](${image.url})`)
  await expect(page.getByRole('status').filter({ hasText: '所有更改已保存' })).toBeVisible()

  expect((await request.get(`/api/content/${record.slug}`)).status()).toBe(404)
  const refreshed = await page.reload()
  expect(refreshed?.headers()['cache-control']).toContain('no-store')
  await page.locator('[data-app-ready="true"]').waitFor()
  await expect(page.getByLabel('Markdown 正文')).toContainText('私人文字')
  await page.screenshot({ path: testInfo.outputPath('editor-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBeFalsy()
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await expect(page.locator('.editor-preview')).toContainText('私人文字')
  await page.screenshot({ path: testInfo.outputPath('editor-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 960 })
  let releasePublish!: () => void
  const publishGate = new Promise<void>(resolve => { releasePublish = resolve })
  await page.route('**/api/admin/content', async route => {
    if (route.request().method() === 'POST' && route.request().postDataJSON()?.action === 'publish') await publishGate
    await route.continue()
  })
  const publishing = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith('/api/admin/content') && req.postDataJSON()?.action === 'publish')
  await page.getByRole('button', { name: '发布', exact: true }).click()
  await publishing
  await page.getByLabel('Markdown 正文').fill('发布请求尚未完成时继续输入的文字')
  releasePublish()

  await expect(page.getByRole('status').filter({ hasText: '已发布，读者现在可以看到这个版本。' })).toBeVisible()
  expect((await request.get(`/api/content/${record.slug}`)).status()).toBe(200)
  expect((await request.get(image.url)).status()).toBe(200)
  await expect(page.getByLabel('Markdown 正文')).toContainText('发布请求尚未完成时继续输入的文字')
  await expect(page.getByRole('status').filter({ hasText: '所有更改已保存' })).toBeVisible()
  await page.unroute('**/api/admin/content')
  const unpublishedImage = await page.request.post('/api/admin/upload', { headers: { origin }, multipart: { contentId: record.id, file: { name: 'draft-only.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aH0sAAAAASUVORK5CYII=', 'base64') } } }).then(r => r.json())
  await page.getByLabel('Markdown 正文').fill(`后续的秘密修改\n\n![未发布图片](${unpublishedImage.url})`)
  await expect(page.getByRole('status').filter({ hasText: '所有更改已保存' })).toBeVisible()
  expect((await request.get(unpublishedImage.url)).status()).toBe(404)
  const publicRecord = await request.get(`/api/content/${record.slug}`).then(r => r.json())
  expect(publicRecord.body).not.toContain('秘密修改')
  const conflict = await page.request.post('/api/admin/content', { headers: { origin }, data: { ...record, action: 'save' } })
  expect(conflict.status()).toBe(409)
  const backup = await page.request.get('/api/admin/backup').then(r => r.json())
  expect(backup.content.some((d: any) => d.id === record.id)).toBeTruthy()
  const restored = await page.request.post('/api/admin/backup', { headers: { origin }, data: backup })
  expect(restored.ok()).toBeTruthy()
  expect((await restored.json()).skipped).toBeGreaterThan(0)
  const restoreOrigin = 'http://127.0.0.1:3101'
  const recovery = await playwright.request.newContext({ baseURL: restoreOrigin })
  const recoveryLogin = await recovery.post('/api/auth', { headers: { origin: restoreOrigin }, data: { password } })
  expect(recoveryLogin.ok()).toBeTruthy()
  const recoveryImport = await recovery.post('/api/admin/backup', { headers: { origin: restoreOrigin }, data: backup })
  expect(recoveryImport.ok()).toBeTruthy()
  expect((await recoveryImport.json()).imported).toBeGreaterThan(0)
  const recovered = await request.get(`${restoreOrigin}/api/content/${record.slug}`).then(r => r.json())
  expect(recovered.body).toBe(publicRecord.body)
  expect((await request.get(`${restoreOrigin}${image.url}`)).status()).toBe(200)
  expect((await request.get(`${restoreOrigin}${unpublishedImage.url}`)).status()).toBe(404)
  const recoveryBackup = await recovery.get('/api/admin/backup').then(r => r.json())
  expect(recoveryBackup.content.find((d: any) => d.id === record.id).body).toContain('秘密修改')
  await recovery.dispose()

  await page.getByRole('button', { name: '撤回发布' }).click()
  await expect(page.getByRole('status').filter({ hasText: '已撤回' })).toBeVisible()
  expect((await request.get(image.url)).status()).toBe(404)
  expect((await request.get(`/api/content/${record.slug}`)).status()).toBe(404)
  expect(JSON.stringify(await request.get(`/api/content?q=${encodeURIComponent(title)}`).then(r => r.json()))).not.toContain(title)
})
