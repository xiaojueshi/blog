test('多尺寸页面可用且无横向溢出，保存实际截图', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 960 })
    for (const path of ['/', '/articles', '/articles/quiet-design', '/articles/edge-notes', '/articles/markdown-guide', '/garden', '/projects', '/about', '/admin']) {
      await page.goto(path)
      await page.evaluate(() => document.fonts.ready)
      await expect(page.locator('h1')).toBeVisible()
      if (path.endsWith('/edge-notes')) await expect(page.locator('.mermaid svg')).toBeVisible()
      if (path.endsWith('/markdown-guide')) await expect(page.locator('.katex')).toBeVisible()
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)
      expect(overflow, `${path} 在 ${width}px 不应横向溢出`).toBeFalsy()
      if (path === '/') await page.screenshot({ path: testInfo.outputPath(`${width}-home-viewport.png`), animations: 'disabled' })
      await page.screenshot({ path: testInfo.outputPath(`${width}-${path.replaceAll('/', '_') || 'home'}.png`), fullPage: true, animations: 'disabled' })
    }
  }
  expect(errors).toEqual([])
})
