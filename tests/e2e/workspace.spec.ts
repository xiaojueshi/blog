test('SSR 在禁用 JavaScript 时仍可阅读，减少动效时保留内容', async ({ browser, page }) => {
  const context = await browser.newContext({ javaScriptEnabled: false })
  const reader = await context.newPage()
  await reader.goto(`${origin}/articles/quiet-design`)
  await expect(reader.getByRole('heading', { name: '好的界面，是让复杂消失', exact: true })).toBeVisible()
  await expect(reader.locator('.prose')).toContainText('舒适的行宽')
  await context.close()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('link', { name: '开始阅读', exact: true })).toBeVisible()
})
